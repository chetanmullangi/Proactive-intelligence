export function kpiById(id) {
  return kpis.find((k) => k.id === id)
}

export function daysStaleFor(kpi) {
  // From KPI_BASELINE at generation time; core claims tables are 69-72d stale,
  // FACT_CLAIM_PAYMENT is fresh (9d).
  if (kpi.table.includes('FACT_CLAIM_PAYMENT')) return 9
  if (kpi.table.includes('PHARMACY_CLAIM')) return 69
  return 72
}
